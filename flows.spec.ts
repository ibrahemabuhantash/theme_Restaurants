test("localized URLs preserve RTL while restoring branch preferences and surviving malformed storage", async ({ page }) => {
  const errors: string[] = []
  page.on("pageerror", (error) => errors.push(error.message))
  page.on("console", (message) => {
    if (/hydration|did not match/i.test(message.text())) errors.push(message.text())
  })
  await page.addInitScript(() => {
    localStorage.setItem("manara-language", JSON.stringify("ar"))
    localStorage.setItem("manara-branch", JSON.stringify("marina"))
    localStorage.setItem("manara-favorites", JSON.stringify([2]))
    localStorage.setItem("manara-cart", "{broken")
  })
  await page.goto("/ar/menu")
  await expect(page.locator("html")).toHaveAttribute("dir", "rtl")
  await expect(page.locator(".header select")).toHaveValue("marina")
  await expect(page.locator(".dish-card")).not.toHaveCount(0)
  await page.reload()
  await expect(page.locator(".header select")).toHaveValue("marina")
  expect(errors).toEqual([])
})

