test("core layouts do not overflow in English or Arabic", async ({ page }) => {
  await page.goto("/")
  await page.evaluate(() => localStorage.setItem("manara-cart", JSON.stringify([
    { key: "layout-test", id: 2, qty: 1, price: 22, size: "Regular", extras: [], notes: "" },
  ])))
  for (const lang of ["en", "ar"]) {
    await page.evaluate((value) => localStorage.setItem("manara-language", JSON.stringify(value)), lang)
    for (const width of [320, 375, 768, 1280]) {
      await page.setViewportSize({ width, height: 900 })
      for (const path of ["/", "/menu", "/food/1", "/cart", "/checkout"]) {
        await page.goto(lang === "ar" ? `/ar${path === "/" ? "" : path}` : path)
        await expect(page.locator("main")).toBeVisible()
        const overflow = await page.evaluate(() => document.documentElement.scrollWidth - innerWidth)
        expect(overflow, `${lang} ${width}px ${path}`).toBeLessThanOrEqual(1)
      }
    }
  }
})
